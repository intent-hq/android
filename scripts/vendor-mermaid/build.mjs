// Reproduce the shipped bundle: cd scripts/vendor-mermaid && npm ci && npm run build
// No frontend checkout, CDN, or Node tooling is needed at app runtime.
import { build } from 'esbuild';
import { readFile, writeFile, readdir, stat } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const directory = dirname(fileURLToPath(import.meta.url));
const output = resolve(directory, '../../app/src/main/assets/mermaid');
const lock = JSON.parse(await readFile(resolve(directory, 'package-lock.json'), 'utf8'));
const peleVersion = lock.packages['node_modules/pele'].version;

await build({
  absWorkingDir: directory,
  entryPoints: ['entry.js'],
  outfile: resolve(output, 'pele.bundle.js'),
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome87'],
  legalComments: 'inline',
  banner: { js: `/* Pele ${peleVersion}. Generated by scripts/vendor-mermaid/build.mjs. See NOTICE.txt. */` },
});

const notices = [
  'Intent Android Mermaid renderer — third-party notices',
  'Pele and its bundled third-party notices are listed below.',
  'Additional license comments from bundled source are preserved inline.',
];

// Include full license texts, not just SPDX names. Runtime distributions can
// contain prebundled modules, so retain their dependency notices conservatively.
for (const [path, metadata] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b))) {
  if (!path || metadata.dev) continue;
  const root = resolve(directory, path);
  const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
  const names = (await readdir(root)).filter(name => /^(licen[cs]e|copying|notice)/i.test(name)).sort();
  const texts = [];
  for (const name of names) {
    if ((await stat(resolve(root, name))).isFile()) {
      texts.push(`${name}\n\n${(await readFile(resolve(root, name), 'utf8')).trim()}`);
    }
  }
  if (!texts.length) {
    const readme = await readFile(resolve(root, 'README.md'), 'utf8');
    const licenseSection = readme.match(/^## License\s*\n([\s\S]*?)(?=^## |$(?![\s\S]))/m);
    if (licenseSection) texts.push(licenseSection[1].trim());
  }
  if (!texts.length) throw new Error(`Missing full license text for ${pkg.name}`);
  notices.push(`\n${'='.repeat(72)}\n${pkg.name} ${pkg.version}\nLicense: ${pkg.license}\n\n${texts.join('\n\n')}`);
}
await writeFile(resolve(output, 'NOTICE.txt'), `${notices.join('\n')}\n`);

const bundle = await readFile(resolve(output, 'pele.bundle.js'));
const manifest = {
  pele: peleVersion,
  esbuild: lock.packages['node_modules/esbuild'].version,
  sha256: createHash('sha256').update(bundle).digest('hex'),
  packageLockSha256: createHash('sha256').update(await readFile(resolve(directory, 'package-lock.json'))).digest('hex'),
};
await writeFile(resolve(output, 'vendor.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`Bundled Pele ${manifest.pele} (${bundle.length} bytes, SHA-256 ${manifest.sha256}).`);
